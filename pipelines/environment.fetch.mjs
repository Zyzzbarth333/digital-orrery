// pipelines/environment.fetch.mjs
//
// Builds the environment model's data (docs/physics/environment.md):
//
//   npm run fetch:environment
//
// - src/physics/egm2008.js: the Earth's gravity field, EGM2008 (NGA), fully
//   normalised C and S to degree and order 70, tide-free. Read from GFZ's
//   ICGEM copy of the model, which lists it by degree, so only the first
//   ~0.3 MB of the 240 MB file is read.
// - src/physics/grail.js: the Moon's gravity field, GRAIL GL0660B (JPL), to
//   degree and order 100, from NASA's Planetary Data System (the first ~1 MB
//   of the 26.7 MB file).
// - src/physics/jgmess160a.js: Mercury's gravity field, JGMESS160A (JPL,
//   MESSENGER), to degree and order 80, and the Mercury-fixed frame it was
//   solved in, from the PDS Geosciences Node (1.6 MB).
// - src/physics/mgnp180u.js: Venus's gravity field, MGNP180U (JPL,
//   Magellan), to degree and order 80, from the PDS Geosciences Node
//   (2.0 MB).
// - public/data/spaceweather.json: the daily solar radio flux F10.7 (observed,
//   and its 81-day centred mean) and the daily geomagnetic Ap, 2000 to the
//   end of CelesTrak's predictions, from CelesTrak's SW-All.csv (T. S. Kelso,
//   from NOAA SWPC and GFZ Potsdam data). The drag model's MET atmosphere
//   reads them for the date.
// Raw downloads are cached in ~/.cache/digital-orrery.

import fs from 'node:fs';
import dns from 'node:dns';

dns.setDefaultResultOrder('ipv4first');
const CACHE = `${process.env.HOME}/.cache/digital-orrery`;
const N = 70;

// ---- EGM2008 to degree N ----
const EGM_URL = 'https://icgem.gfz-potsdam.de/getmodel/gfc/c50128797a9cb62e936337c890e4425f03f0461d7329b09a8cc8561504465340/EGM2008.gfc';
const egmCache = `${CACHE}/egm2008/EGM2008_to${N}.gfc`;
fs.mkdirSync(`${CACHE}/egm2008`, { recursive: true });
if (!fs.existsSync(egmCache)) {
  const ctrl = new AbortController();
  const res = await fetch(EGM_URL, { signal: ctrl.signal, headers: { 'User-Agent': 'digital-orrery environment model' } });
  if (!res.ok) throw new Error(`EGM2008: HTTP ${res.status}`);
  const reader = res.body.getReader(), dec = new TextDecoder();
  let text = '';
  // Read until a coefficient of degree N + 1 appears, then stop the transfer.
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    text += dec.decode(value, { stream: true });
    if (new RegExp(`\\ngfc\\s+${N + 1}\\s`).test(text)) { ctrl.abort(); break; }
  }
  fs.writeFileSync(egmCache, text);
}
const gfc = fs.readFileSync(egmCache, 'utf8');
const head = Object.fromEntries(gfc.slice(0, gfc.indexOf('end_of_head')).split('\n').map((l) => l.trim().split(/\s+/)).filter((x) => x.length >= 2).map(([k, v]) => [k, v]));
const C = [], S = [];
for (let n = 0; n <= N; n++) { C.push(new Array(n + 1).fill(0)); S.push(new Array(n + 1).fill(0)); }
let count = 0;
for (const line of gfc.slice(gfc.indexOf('end_of_head')).split('\n')) {
  const f = line.trim().split(/\s+/);
  if (f[0] !== 'gfc') continue;
  const n = Number(f[1]), m = Number(f[2]);
  if (n > N) break;
  C[n][m] = Number(f[3].replace('d', 'e')); S[n][m] = Number(f[4].replace('d', 'e'));
  count++;
}
const gm = Number(head.earth_gravity_constant) / 1e9, radius = Number(head.radius) / 1000;
const js = `// src/physics/egm2008.js (generated by environment.fetch.mjs: do not edit)
//
// The Earth's gravity field: EGM2008 (Pavlis et al. 2012, NGA), fully
// normalised coefficients to degree and order ${N}, ${head.tide_system}, read from
// GFZ's ICGEM copy. C[n][m], S[n][m]; GM in km^3/s^2, radius in km.
export const EGM2008 = {
  gm: ${gm}, radius: ${radius}, degree: ${N}, tide: '${head.tide_system}',
  C: ${JSON.stringify(C)},
  S: ${JSON.stringify(S)},
};
`;
fs.writeFileSync(new URL('../src/physics/egm2008.js', import.meta.url), js);
console.log(`egm2008.js: ${count} coefficients to degree ${N}, GM ${gm} km^3/s^2, R ${radius} km (${(js.length / 1024).toFixed(0)} kB)`);

// ---- the Moon: GRAIL GL0660B to degree NM ----
// JPL's lunar field from GRAIL's primary mission (Konopliv et al. 2013),
// fully normalised, reference radius 1738.0 km, in the principal-axis frame
// that DE421 defines. Read from NASA's Planetary Data System, in degree
// order, so only the first ~1 MB of the 26.7 MB file is read.
const NM = 100;
const GRAIL_URL = 'https://pds-geosciences.wustl.edu/grail/grail-l-lgrs-5-rdr-v1/grail_1001/shadr/jggrx_0660b_sha.tab';
const grailCache = `${CACHE}/grail/jggrx_0660b_to${NM}.tab`;
fs.mkdirSync(`${CACHE}/grail`, { recursive: true });
if (!fs.existsSync(grailCache)) {
  const ctrl = new AbortController();
  const res = await fetch(GRAIL_URL, { signal: ctrl.signal });
  if (!res.ok) throw new Error(`GRAIL: HTTP ${res.status}`);
  const reader = res.body.getReader(), dec = new TextDecoder();
  let text = '';
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    text += dec.decode(value, { stream: true });
    if (new RegExp(`\\n\\s*${NM + 1},`).test(text)) { ctrl.abort(); break; }
  }
  fs.writeFileSync(grailCache, text);
}
{
  const rows = fs.readFileSync(grailCache, 'utf8').split(/\r?\n/).map((l) => l.split(',').map((x) => x.trim())).filter((f) => f.length >= 4 && f[0] !== '');
  const [radius, gm] = rows[0].map(Number);
  const MC = [], MS = [];
  for (let n = 0; n <= NM; n++) { MC.push(new Array(n + 1).fill(0)); MS.push(new Array(n + 1).fill(0)); }
  MC[0][0] = 1;
  let k = 0;
  for (const f of rows.slice(1)) {
    const n = Number(f[0]), m = Number(f[1]);
    if (!(n <= NM)) break;
    MC[n][m] = Number(f[2]); MS[n][m] = Number(f[3]); k++;
  }
  const js = `// src/physics/grail.js (generated by environment.fetch.mjs: do not edit)
//
// The Moon's gravity field: GRAIL GL0660B (Konopliv et al. 2013, JPL),
// fully normalised coefficients to degree and order ${NM}, in the principal-axis
// frame of DE421, from NASA's Planetary Data System. C[n][m], S[n][m]; GM in
// km^3/s^2, radius in km. PA_TO_ME turns principal-axis coordinates into
// mean-Earth/polar-axis ones (r_ME = PA_TO_ME r_PA), as CSPICE gives it from
// NAIF's moon_de440_250416.tf (MOON_PA_DE440 to MOON_ME): rotations of
// 67.85", 78.69" and 0.28".
export const GRAIL = {
  gm: ${gm}, radius: ${radius}, degree: ${NM},
  C: ${JSON.stringify(MC)},
  S: ${JSON.stringify(MS)},
};
export const PA_TO_ME = [
  [0.9999998731138765, -0.00032895865791419379, 0.00038152120821145725],
  [0.00032895919698748533, 0.99999994589201047, -1.3502060036227025e-06],
  [-0.00038152074340615683, 1.4757107425872328e-06, 0.99999992721986974],
];
`;
  fs.writeFileSync(new URL('../src/physics/grail.js', import.meta.url), js);
  console.log(`grail.js: ${k} coefficients to degree ${NM}, GM ${gm} km^3/s^2, R ${radius} km (${(js.length / 1024).toFixed(0)} kB)`);
}

// ---- Mercury and Venus: PDS SHADR tables ----
// The PDS's spherical-harmonic ASCII data record: a header row (reference
// radius km, GM km^3/s^2, its uncertainty, degree, order, normalisation
// flag, reference longitude, latitude), then a row per coefficient (n, m,
// C, S, sigma C, sigma S), comma-separated. MGNP180U's file carries its
// PDS3 label in front; the first row of numbers starts the table.
async function shadr(url, cacheFile) {
  fs.mkdirSync(cacheFile.slice(0, cacheFile.lastIndexOf('/')), { recursive: true });
  if (!fs.existsSync(cacheFile)) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    fs.writeFileSync(cacheFile, Buffer.from(await res.arrayBuffer()));
  }
  // (MGNP180U's header row follows an SFDU marker on the same line: the
  // first field's last word is the number.)
  const rows = fs.readFileSync(cacheFile, 'latin1').split(/\r?\n/).map((l) => l.split(',').map((x, i) => (i ? x.trim() : x.trim().split(/\s+/).at(-1))))
    .filter((f) => f.length >= 6 && f.slice(0, 6).every((x) => x !== '' && Number.isFinite(Number(x))));
  const [radius, gm, , degree, order, norm] = rows[0].map(Number);
  if (norm !== 1) throw new Error(`${url}: not fully normalised`);
  return { radius, gm, degree, order, rows: rows.slice(1).map((f) => f.slice(0, 4).map(Number)) };
}
function truncate(T, N) {
  const C = [], S = [];
  for (let n = 0; n <= N; n++) { C.push(new Array(n + 1).fill(0)); S.push(new Array(n + 1).fill(0)); }
  C[0][0] = 1;
  let k = 0;
  for (const [n, m, c, s] of T.rows) if (n <= N) { C[n][m] = c; S[n][m] = s; k++; }
  return { C, S, k };
}
// To degree 100, GRAIL's: past it the fields are mostly noise at the
// heights craft fly (190 kB each). geopotential.js runs on fully normalised
// coefficients, so it has no limit of its own.
const NP = 100;
{
  // JGMESS160A (Konopliv et al. 2020): MESSENGER's tracking, 2011-2015. Its
  // label gives the Mercury-fixed frame the field was solved in, pole and
  // spin estimated with it: RA 281.0138 - 0.0328 T, Dec 61.4161 - 0.0049 T
  // (deg; T Julian centuries TDB from J2000), W 329.75 + 6.138514 d (deg; d
  // days). The IAU's (pck00011) differs by 0.004 deg at the pole and 0.15 deg
  // in W. The degree 2 terms leave out the permanent tide (k2 = 0.53).
  const T = await shadr('https://pds-geosciences.wustl.edu/messenger/mess-h-rss_mla-5-sdp-v1/messrs_1001/data/shadr/jgmess_160a_sha.tab', `${CACHE}/gravity-mercury/jgmess_160a_sha.tab`);
  const { C: HC, S: HS, k } = truncate(T, NP);
  const js = `// src/physics/jgmess160a.js (generated by environment.fetch.mjs: do not edit)
//
// Mercury's gravity field: JGMESS160A (Konopliv et al. 2020, JPL), from
// MESSENGER's tracking, fully normalised coefficients to degree and order ${NP}
// of ${T.degree}, from NASA's Planetary Data System. C[n][m], S[n][m]; GM in
// km^3/s^2, radius in km. The degree 2 terms leave out the permanent tide.
// FRAME: the Mercury-fixed frame the field was solved in (its PDS label):
// pole RA ra[0] + ra[1] T, Dec dec[0] + dec[1] T (deg, T Julian centuries
// TDB from J2000), prime meridian W = pm[0] + pm[1] d (deg, d days TDB).
export const JGMESS160A = {
  gm: ${T.gm}, radius: ${T.radius}, degree: ${NP},
  C: ${JSON.stringify(HC)},
  S: ${JSON.stringify(HS)},
};
export const MERCURY_FRAME = { ra: [281.0138, -0.0328], dec: [61.4161, -0.0049], pm: [329.75, 6.138514] };
`;
  fs.writeFileSync(new URL('../src/physics/jgmess160a.js', import.meta.url), js);
  console.log(`jgmess160a.js: ${k} coefficients to degree ${NP}, GM ${T.gm} km^3/s^2, R ${T.radius} km (${(js.length / 1024).toFixed(0)} kB)`);
}
{
  // MGNP180U (Konopliv et al. 1999): Magellan's and Pioneer Venus Orbiter's
  // tracking. Its label names no frame; the Magellan fields are referred to
  // the IAU's Venus-fixed frame (pck00011: RA 272.76, Dec 67.16, W 160.20 -
  // 1.4813688 d), as the app orients Venus.
  const T = await shadr('https://pds-geosciences.wustl.edu/mgn/mgn-v-rss-5-gravity-l2-v1/mg_5201/gravity/shgj180u.a01', `${CACHE}/gravity-venus/shgj180u.a01`);
  const { C: VC, S: VS, k } = truncate(T, NP);
  const js = `// src/physics/mgnp180u.js (generated by environment.fetch.mjs: do not edit)
//
// Venus's gravity field: MGNP180U (Konopliv et al. 1999, JPL), from
// Magellan's and Pioneer Venus Orbiter's tracking, fully normalised
// coefficients to degree and order ${NP} of ${T.degree}, from NASA's Planetary Data
// System (shgj180u.a01). C[n][m], S[n][m]; GM in km^3/s^2, radius in km.
// FRAME: the IAU's Venus-fixed frame (as MERCURY_FRAME in jgmess160a.js).
export const MGNP180U = {
  gm: ${T.gm}, radius: ${T.radius}, degree: ${NP},
  C: ${JSON.stringify(VC)},
  S: ${JSON.stringify(VS)},
};
export const VENUS_FRAME = { ra: [272.76, 0], dec: [67.16, 0], pm: [160.20, -1.4813688] };
`;
  fs.writeFileSync(new URL('../src/physics/mgnp180u.js', import.meta.url), js);
  console.log(`mgnp180u.js: ${k} coefficients to degree ${NP}, GM ${T.gm} km^3/s^2, R ${T.radius} km (${(js.length / 1024).toFixed(0)} kB)`);
}

// ---- space weather ----
const SW_URL = 'https://celestrak.org/SpaceData/SW-All.csv';
const swCache = `${CACHE}/spaceweather/SW-All.csv`;
fs.mkdirSync(`${CACHE}/spaceweather`, { recursive: true });
if (!fs.existsSync(swCache)) {
  const res = await fetch(SW_URL);
  if (!res.ok) throw new Error(`space weather: HTTP ${res.status}`);
  fs.writeFileSync(swCache, await res.text());
}
const lines = fs.readFileSync(swCache, 'utf8').trim().split(/\r?\n/), cols = lines[0].split(',');
const col = (name) => cols.indexOf(name);
const iDate = col('DATE'), iF = col('F10.7_OBS'), iFbar = col('F10.7_OBS_CENTER81'), iAp = col('AP_AVG'), iType = col('F10.7_DATA_TYPE');
const days = [];
for (const l of lines.slice(1)) {
  const f = l.split(',');
  if (f[iDate] < '2000-01-01') continue;
  const F = Number(f[iF]), Fbar = Number(f[iFbar]), Ap = Number(f[iAp]);
  if (![F, Fbar, Ap].every(Number.isFinite) || F <= 0) continue;
  days.push([f[iDate], Number(F.toFixed(1)), Number(Fbar.toFixed(1)), Number(Ap.toFixed(1)), f[iType]]);
}
const out = {
  source: 'CelesTrak SW-All.csv (T. S. Kelso; NOAA SWPC and GFZ Potsdam data)', url: SW_URL,
  fields: ['date', 'F10.7 observed', 'F10.7 81-day centred mean (observed)', 'Ap daily', 'type'],
  start: days[0][0], days: days.map((d) => d.slice(1, 4)), lastObserved: days.filter((d) => d[4] === 'OBS').at(-1)?.[0],
};
const path = new URL('../public/data/spaceweather.json', import.meta.url);
fs.mkdirSync(new URL('.', path), { recursive: true });
fs.writeFileSync(path, JSON.stringify(out));
console.log(`spaceweather.json: ${days.length} days from ${out.start} to ${days.at(-1)[0]} (observed to ${out.lastObserved}), ${(fs.statSync(path).size / 1024).toFixed(0)} kB`);
