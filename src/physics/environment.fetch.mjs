// src/physics/environment.fetch.mjs
//
// Builds the environment model's data (docs/physics/environment.md):
//
//   npm run fetch:environment
//
// - src/physics/egm2008.js: the Earth's gravity field, EGM2008 (NGA), fully
//   normalised C and S to degree and order 70, tide-free. Read from GFZ's
//   ICGEM copy of the model, which lists it by degree, so only the first
//   ~0.3 MB of the 240 MB file is read.
// - public/data/spaceweather.json: the daily solar radio flux F10.7 (observed,
//   and its 81-day centred mean) and the daily geomagnetic Ap, 2000 to the
//   end of CelesTrak's predictions, from CelesTrak's SW-All.csv (T. S. Kelso,
//   from NOAA SWPC and GFZ Potsdam data). The drag model's MET atmosphere
//   reads them for the date.
// Raw downloads are cached in ~/.cache/digital-orrery.

import fs from 'node:fs';
import dns from 'node:dns';

dns.setDefaultResultOrder('ipv4first');
const CACHE = `${process.env.HOME}/.cache/digital-orrery`;
const N = 70;

// ---- EGM2008 to degree N ----
const EGM_URL = 'https://icgem.gfz-potsdam.de/getmodel/gfc/c50128797a9cb62e936337c890e4425f03f0461d7329b09a8cc8561504465340/EGM2008.gfc';
const egmCache = `${CACHE}/egm2008/EGM2008_to${N}.gfc`;
fs.mkdirSync(`${CACHE}/egm2008`, { recursive: true });
if (!fs.existsSync(egmCache)) {
  const ctrl = new AbortController();
  const res = await fetch(EGM_URL, { signal: ctrl.signal, headers: { 'User-Agent': 'digital-orrery environment model' } });
  if (!res.ok) throw new Error(`EGM2008: HTTP ${res.status}`);
  const reader = res.body.getReader(), dec = new TextDecoder();
  let text = '';
  // Read until a coefficient of degree N + 1 appears, then stop the transfer.
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    text += dec.decode(value, { stream: true });
    if (new RegExp(`\\ngfc\\s+${N + 1}\\s`).test(text)) { ctrl.abort(); break; }
  }
  fs.writeFileSync(egmCache, text);
}
const gfc = fs.readFileSync(egmCache, 'utf8');
const head = Object.fromEntries(gfc.slice(0, gfc.indexOf('end_of_head')).split('\n').map((l) => l.trim().split(/\s+/)).filter((x) => x.length >= 2).map(([k, v]) => [k, v]));
const C = [], S = [];
for (let n = 0; n <= N; n++) { C.push(new Array(n + 1).fill(0)); S.push(new Array(n + 1).fill(0)); }
let count = 0;
for (const line of gfc.slice(gfc.indexOf('end_of_head')).split('\n')) {
  const f = line.trim().split(/\s+/);
  if (f[0] !== 'gfc') continue;
  const n = Number(f[1]), m = Number(f[2]);
  if (n > N) break;
  C[n][m] = Number(f[3].replace('d', 'e')); S[n][m] = Number(f[4].replace('d', 'e'));
  count++;
}
const gm = Number(head.earth_gravity_constant) / 1e9, radius = Number(head.radius) / 1000;
const js = `// src/physics/egm2008.js (generated by environment.fetch.mjs: do not edit)
//
// The Earth's gravity field: EGM2008 (Pavlis et al. 2012, NGA), fully
// normalised coefficients to degree and order ${N}, ${head.tide_system}, read from
// GFZ's ICGEM copy. C[n][m], S[n][m]; GM in km^3/s^2, radius in km.
export const EGM2008 = {
  gm: ${gm}, radius: ${radius}, degree: ${N}, tide: '${head.tide_system}',
  C: ${JSON.stringify(C)},
  S: ${JSON.stringify(S)},
};
`;
fs.writeFileSync(new URL('./egm2008.js', import.meta.url), js);
console.log(`egm2008.js: ${count} coefficients to degree ${N}, GM ${gm} km^3/s^2, R ${radius} km (${(js.length / 1024).toFixed(0)} kB)`);

// ---- space weather ----
const SW_URL = 'https://celestrak.org/SpaceData/SW-All.csv';
const swCache = `${CACHE}/spaceweather/SW-All.csv`;
fs.mkdirSync(`${CACHE}/spaceweather`, { recursive: true });
if (!fs.existsSync(swCache)) {
  const res = await fetch(SW_URL);
  if (!res.ok) throw new Error(`space weather: HTTP ${res.status}`);
  fs.writeFileSync(swCache, await res.text());
}
const lines = fs.readFileSync(swCache, 'utf8').trim().split(/\r?\n/), cols = lines[0].split(',');
const col = (name) => cols.indexOf(name);
const iDate = col('DATE'), iF = col('F10.7_OBS'), iFbar = col('F10.7_OBS_CENTER81'), iAp = col('AP_AVG'), iType = col('F10.7_DATA_TYPE');
const days = [];
for (const l of lines.slice(1)) {
  const f = l.split(',');
  if (f[iDate] < '2000-01-01') continue;
  const F = Number(f[iF]), Fbar = Number(f[iFbar]), Ap = Number(f[iAp]);
  if (![F, Fbar, Ap].every(Number.isFinite) || F <= 0) continue;
  days.push([f[iDate], Number(F.toFixed(1)), Number(Fbar.toFixed(1)), Number(Ap.toFixed(1)), f[iType]]);
}
const out = {
  source: 'CelesTrak SW-All.csv (T. S. Kelso; NOAA SWPC and GFZ Potsdam data)', url: SW_URL,
  fields: ['date', 'F10.7 observed', 'F10.7 81-day centred mean (observed)', 'Ap daily', 'type'],
  start: days[0][0], days: days.map((d) => d.slice(1, 4)), lastObserved: days.filter((d) => d[4] === 'OBS').at(-1)?.[0],
};
const path = new URL('../../public/data/spaceweather.json', import.meta.url);
fs.mkdirSync(new URL('.', path), { recursive: true });
fs.writeFileSync(path, JSON.stringify(out));
console.log(`spaceweather.json: ${days.length} days from ${out.start} to ${days.at(-1)[0]} (observed to ${out.lastObserved}), ${(fs.statSync(path).size / 1024).toFixed(0)} kB`);
